// Loops
// FOR , While , Do While Loop

// FOR LOOP
for (let i=0;i<5;i++){ // Intialization , Stopping Condition , Updation
    console.log("Hello");
}

// Sum of 1 to 5
let sum = 0;
for(let k=1;k<=5;k++){
    sum = sum + k;
}
console.log(sum);

// factorial
let n = prompt("Enter a number");
let fact = 1;
for(let j=1;j<=n;j++){
    fact = fact * j;
}
console.log(fact);

