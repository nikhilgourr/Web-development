// String Methods 

const str = "apna college";
let str1 = " is the best";

// toUpperCase()
console.log(str.toUpperCase());

// toUpperCase()
console.log(str.toUpperCase());

// str.trim()
console.log(str.trim()); // Removes Extra White Spaces

// Slice()
console.log(str.slice(0,5));

// concat()
console.log(str.concat(str1));

// replace()
const newStr = str.replace("college","college mlsu");
console.log(newStr);

// charAt()
console.log(str.charAt(0)); // Finds the given index characters
console.log(str.charAt(1));
